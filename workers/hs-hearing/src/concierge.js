/* 加盟店から届いた1通の意図を見分ける。
   返す: "answer"(回答) | "question"(質問) | "other"(お礼・雑談など)

   見分けの順序に意味がある。
     1) 番号つき(1) 2) / ①②)で始まる → 回答。こちらの複数設問への返事である。
     2) 疑問の形(末尾が ？、または「〜ますか」「大丈夫」等) → 質問。
     3) それ以外 → この関係の既定は回答収集なので、回答として扱う。

   誤分類の害は非対称である。
     ・質問を回答と誤ると: 問いを無視して、答えたことにしてしまう(実害・大)。
     ・回答を質問と誤ると: 取り込まないだけ。生文は残り、人が拾える(実害・小)。
   だから、疑問の兆しがあれば質問側に倒す。 */
export function partnerIntent(text) {
  const t = String(text || "").trim();
  if (!t) return "other";

  // 1) 番号つきの返事は、回答。
  if (/^[\s　]*(?:\(?[1-9１-９]\)?[)）.．、,:：]|[①-⑨])/.test(t)) return "answer";

  // 2) 疑問の形か。末尾の ？ が最も強い兆し。
  const endsQ = /[?？]\s*$/.test(t);
  const interrog = /(ますか|ますでしょうか|ですか[。\s]*$|でしょうか|できますか|大丈夫|平気|ダメ(に|です|でしょう)|止めたら|やめたら|途中で(止|や|中断)|どうすれ|どうしたら|どうやって|どうなる|いつまで|いつから|どこに|どこで|なぜ|どちら|何を(書|記|入力|すれ)|教えて(ください|くれ|ほしい)|わからな|分からな|不安|平問|困っ)/.test(t);
  if (endsQ || interrog) return "question";

  return "answer";
}

/* 決まった問いには、決まった答えを返す(機械で確実に。LLM に頼らない)。
   台帳に無い問いは null を返し、呼ぶ側が LLM か大賀に回す。
   ここで返す文は FACT_SHEET の範囲内でだけ具体を述べる。 */
export function conciergeFAQ(text) {
  const t = String(text || "");

  // 途中で止める / 保存 / 続き
  if (/(途中|とちゅう|一時|下書き|保存|続き|あとで|後で)/.test(t) &&
      /(止|や|やめ|中断|大丈夫|ダメ|平気|消え|なくな|保存|送信|続|できま)/.test(t)) {
    return "途中で止めても大丈夫です。区切りのいいところで一度「送信」を押していただければ、そこまでが保存され、同じリンクからいつでも続きを足せます(前の内容は消えません)。送信するまでは保存されないので、長く入力されるときは、こまめに送信いただけると安心です。";
  }
  // 止めたら/やめたら + ダメ(平田様の実文)。上に掛からない書き方に備える。
  if (/(止めたら|やめたら|中断).*(ダメ|だめ|大丈夫|平気|消え|なくな)/.test(t) ||
      /(ダメ|だめ|大丈夫|平気).*(止め|やめ|中断|途中)/.test(t)) {
    return "途中で止めても大丈夫です。「送信」を押したところまでが保存され、同じリンクから続きを足せます(前の内容は消えません)。送信するまでは保存されないので、こまめに送信いただけると安心です。";
  }
  // 何を書けばいいか / 全部埋める必要があるか / 分からない
  if (/(何を(書|記|入力)|どこまで(書|記|入力)|全部(書|記|入力|埋め)|空欄|埋めな(く|きゃ)|わからな|分からな|書けな|書き方)/.test(t)) {
    return "分かるところだけで結構です。空欄のまま送っていただいても構いません。足りないところは、こちらから改めてお伺いしますので、ご負担のない範囲でお願いします。";
  }
  // 料金(通常は上流で捕まえているが、念のため二重の網)
  if (/(金額|料金|価格|費用|いくら|値段|支払|請求|割引|値引)/.test(t)) {
    return "料金・金額については、担当の大賀からご案内します。少々お待ちください。";
  }
  return null;
}

/* ------------------------------------------------------------------------
   2026-09-30 返事の形を読む(貼った設問 ↓ 答え)。

   実測(hs-partner-001、HORIZON グループ): 堤さまと森下さまは、こちらの設問を
   トークに貼り、その下に「↓」を置いて答えを書いてくださった。先頭には
   「@HORIZON SHIELD」のメンションが付く。
   これまでは全文をひとかたまりで読んでいたため、
     ・堤さまの答えは、貼った設問の「教えてください」で「質問」と判定され、取り込まれなかった
     ・森下さまの答えは、こちらが訊いた「他社より高いと言われたとき」「仕入れ値」への答えなので
       「金額」「価格」の語が入り、金額の門で「料金の問い合わせ」とされ、取り込まれなかった
   相手はこちらの頼んだとおりに答えている。読み違えていたのはこちらである。

   splitEchoReply は、先頭のメンションを外し、最初の「↓」だけの行で前後に分ける。
   前が貼った設問(echo)、後ろが答え(answer)。矢印の行が無ければ全文が答え。 */
const BOT_MENTION_RE = /@[ 　]*HORIZON[ 　]*SHIELD[ 　]*/gi;
const ARROW_LINE_RE = /^[ 　]*[↓⬇⇩⇓▼▽][↓⬇⇩⇓▼▽️]*[ 　]*(?:(?:回答|答え|返答|ご回答)[ 　]*[:：]?)?[ 　]*$/;
export function splitEchoReply(text) {
  const raw = String(text || "").replace(/\r/g, "");
  const mentioned = /@[ 　]*HORIZON[ 　]*SHIELD/i.test(raw);
  const t = raw.replace(BOT_MENTION_RE, "").trim();
  const lines = t.split("\n");
  const i = lines.findIndex((l) => ARROW_LINE_RE.test(l));
  if (i > 0) {
    const echo = lines.slice(0, i).join("\n").trim();
    const answer = lines.slice(i + 1).join("\n").trim();
    if (echo && answer) return { echo, answer, mentioned };
  }
  return { echo: "", answer: t, mentioned };
}

/* 金額の語。handlePartnerInbound の門と同じ物差し(ここに1つだけ置く)。 */
export const MONEY_WORDS_RE = /(金額|料金|価格|費用|いくら|お値段|値段|支払|お支払|請求|割引|値引|万円|見積[^。]{0,8}金額|プラン[^。]{0,8}料金)/;

/* こちら(運営)へのお金の問い合わせ。掲載料・会費・支払い方法・いくらか、など。
   答えの中に「価格は上がっている」があっても、これには当たらない。 */
export const FEE_INQUIRY_RE = /(掲載料|掲載の料金|掲載費|会費|月額|月々|ご請求|請求書|振込|振り込み|お支払い(方法|先|は|について)|支払い(方法|先|は)|料金(は|って|を教え|について|体系)|費用(は|って|について)|いくらですか|いくらでしょう|いくらかかり|いくらになり|プラン[^。]{0,8}料金|有料(ですか|でしょうか|になり))/;

/* 返事待ちの設問が、そもそも値段の話を訊いているか(仕入れ値・高いと言われた・諸経費・単価など)。
   訊いたことへの答えにお金の語が入るのは当然で、それを料金の問い合わせと読んではいけない。 */
export const PRICE_TOPIC_RE = /(高い|安い|仕入れ|材料|価格|値段|金額|単価|諸経費|費用|相場|値上|値下|見積)/;
export function askedAboutPrices(askedText) {
  return PRICE_TOPIC_RE.test(String(askedText || ""));
}

/* 貼った設問の下に書かれた答えの意図。貼った設問の中の「教えてください」は見ない。
   答えの最後が問いの形で終わるときだけ質問とする(答えの途中の言い回しで質問にしない)。 */
export function answerIntentAfterEcho(answer) {
  const a = String(answer || "").trim();
  if (!a) return "other";
  if (/[?？][ 　]*$/.test(a)) return "question";
  if (/(ますか|ますでしょうか|でしょうか|ですか)[。 　]*$/.test(a)) return "question";
  return "answer";
}

/* 2026-09-30 同じ会社の人に宛てた一言を、こちらへの答えにしない。

   実測(hs-partner-001): 9/27、継続エンリッチの q_en_recent(直近の工事1件)を送ったあと、
   堤さまがそれを HORIZON グループに回し「@森下 真也 明日以後宜しくです!」と書かれた。
   返事待ちが1問だけだったので、これが sole(その質問だけへの返事)として q_en_recent の欄に入った。
   本当の答え(半田市のロールスクリーン)は 9/30 に森下さまから届いたが、そのときは返事待ちが空で、どの欄にも入らなかった。
   9/7 の「@森下 真也 宜しくです!」と同じ形である。

   先頭が公式アカウント以外への @ で、それを除くと短い一言しか残らないものは、社内の申し送りとして扱う。
   答えとして取り込まず、返事待ちも消さず、返事もしない。生の文は aside: に残す。 */
export function isPersonalAside(text) {
  const raw = String(text || "").replace(/\r/g, "").trim();
  if (!/^[@＠]/.test(raw)) return false;
  if (/[@＠][ 　]*HORIZON[ 　]*SHIELD/i.test(raw)) return false;
  const lines = raw.split("\n");
  let rest;
  if (lines[0].length <= 24) rest = lines.slice(1).join("\n");
  else rest = lines[0].replace(/^[@＠][^ 　\n]+(?:[ 　][^ 　\n]+)?/, "") + "\n" + lines.slice(1).join("\n");
  rest = rest.replace(/[@＠][^ 　\n]+/g, "").replace(/[\s　]/g, "");
  return rest.length <= 30;
}
