/* ------------------------------------------------------------------------
   加盟店窓口の「意図を見る層」と、答えてよい事実の台帳。

   なぜ要る (2026-08-25):
     このシステムは、加盟店から入ってくる文を、全部「ヒアリングへの回答」として
     処理していた。だから、加盟店が こちらに 質問してきたときにも、回答として
     取り込もうとし、答えられずに定型文を返した。

     実際に起きたこと。合同会社アップスの平田様が、フォームを書きながら
       「今シートの記載をしてますが、これは途中で止めたらダメになっちゃいますか？」
     と尋ねてこられた。はっきりした、不安まじりの問いである。
     システムは「どの質問への回答か取り違えている可能性があります」と返した。
     問いに、ひとことも答えていない。

     入ってくる文には、少なくとも三つある。
       ・こちらの設問への 回答
       ・こちらへの 質問
       ・ただの一言(お礼、雑談)
     これらを見分けずに全部「回答」として扱うのが、根の間違いだった。

   この層がすること:
     1) 意図を見分ける(partnerIntent)
     2) 質問には、答えてよい事実(FACT_SHEET)からだけ答える(conciergeFAQ)
, 台帳に無いことは答えず、担当の大賀に回す。作り話をしない。

   純粋関数だけを置く(env に触れない)。だから機械で端から端まで確かめられる。
   env を要る返信(LLM 経由)は hearing.js 側に置く。
------------------------------------------------------------------------ */

